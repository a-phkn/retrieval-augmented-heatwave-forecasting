"""
Gate G0 (plan v5, Week 1): honest paired comparisons of the v1 models on the
validation split, using the saved per-seed predictions (evaluation/predict_v1.py)
and the cluster-jackknife test (evaluation/stats.py).

For each (parent -> child) pair and each stratum (all / normal / unusual / extreme,
v1 labels), reports delta RMSE = child - parent with a 95% CI, p-value (t, G-1 df),
number of year x season clusters and how many favour the child. Diebold-Mariano
on per-window MSE (seed-averaged, time-ordered) is reported as a secondary check
for the 'all' stratum only (DM needs a contiguous time series).

Writes evaluation_v2/g0_val_comparison.json and .md. Test split is never read.

Run from repo root (after predict_v1):
    python -m evaluation.compare_v1
"""
from __future__ import annotations

import json
import warnings
from pathlib import Path

import numpy as np
import pandas as pd

from evaluation.stats import dm_test, paired_cluster_test

REPO_ROOT = Path(__file__).resolve().parents[1]
PRED_DIR = REPO_ROOT / "predictions_v1" / "val"
OUT_DIR = REPO_ROOT / "evaluation_v2"
STRATA = ("all", "normal", "unusual", "extreme")
KEY = ["query_date", "lead"]

# (parent, child): the comparisons the v1 claims rest on.
PAIRS = [
    ("persistence", "climatology"),
    ("persistence", "lstm_a1"),
    ("climatology", "lstm_a1"),
    ("lstm_a1", "ra_v1"),  # H2: does retrieval help?
    ("climatology", "ra_v1"),
]


def load(model: str) -> pd.DataFrame | None:
    path = PRED_DIR / f"{model}.parquet"
    return pd.read_parquet(path) if path.exists() else None


def seed_errors(df: pd.DataFrame, mask_key: pd.DataFrame) -> list[np.ndarray]:
    """Per-seed 1-D error arrays, rows aligned to mask_key's (query_date, lead) order."""
    out = []
    for _, g in df.groupby("seed", sort=True):
        g = g.set_index(KEY).loc[pd.MultiIndex.from_frame(mask_key[KEY])]
        out.append(g["error"].to_numpy())
    return out


def window_mse(df: pd.DataFrame) -> pd.Series:
    """Seed-averaged per-window MSE, indexed by query_date (time-ordered)."""
    per_seed = df.assign(se=df["error"] ** 2).groupby(["seed", "query_date"])["se"].mean()
    return per_seed.groupby("query_date").mean().sort_index()


def _labels(df: pd.DataFrame) -> pd.DataFrame:
    """Stratum and cluster per (query_date, lead) from the lowest seed, sorted by key."""
    return df[df["seed"] == df["seed"].min()].sort_values(KEY).reset_index(drop=True)[KEY + ["stratum", "cluster_id"]]


def compare(parent: pd.DataFrame, child: pd.DataFrame, stratum: str) -> dict:
    ref, child_ref = _labels(parent), _labels(child)
    if not ref.equals(child_ref):
        raise ValueError("parent and child predictions disagree on windows, strata or clusters")
    if stratum != "all":
        ref = ref[ref["stratum"] == stratum].reset_index(drop=True)
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        r = paired_cluster_test(
            parent=seed_errors(parent, ref), child=seed_errors(child, ref), cluster_ids=ref["cluster_id"].to_numpy()
        )
        row = r.to_dict()
        if stratum == "all":
            a, b = window_mse(child), window_mse(parent)
            dm = dm_test(a.to_numpy(), b.to_numpy(), dates=a.index)
            row["dm_statistic"], row["dm_p_value"], row["dm_lag"] = dm.statistic, dm.p_value, dm.lag
    row["warnings"] = [str(w.message) for w in caught]
    return row


def fmt_p(p: float) -> str:
    if np.isnan(p):
        return "n/a"
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def main() -> None:
    models = {m: load(m) for m in {m for pair in PAIRS for m in pair}}
    results = []
    for parent, child in PAIRS:
        if models[parent] is None or models[child] is None:
            print(f"skip {parent} -> {child}: predictions missing")
            continue
        for stratum in STRATA:
            row = compare(models[parent], models[child], stratum)
            row.update(parent=parent, child=child, stratum=stratum)
            results.append(row)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    with open(OUT_DIR / "g0_val_comparison.json", "w", encoding="utf-8", newline="\n") as f:
        json.dump({"split": "val", "metric": "rmse", "labels": "v1", "results": results}, f, indent=2, default=float)

    lines = [
        "# G0: validation-split comparisons (v1 labels, RMSE, deg C)",
        "",
        "Generated by `python -m evaluation.compare_v1` from `predictions_v1/val/`.",
        "",
        "| Parent -> child | Stratum | Delta | 95% CI | p | G | Clusters child better | Seeds (p/c) | DM p |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in results:
        ci = "n/a" if np.isnan(r["ci_low"]) else f"[{r['ci_low']:+.3f}, {r['ci_high']:+.3f}]"
        fragile = "*" if r["few_clusters"] else ""
        dm = fmt_p(r["dm_p_value"]) if "dm_p_value" in r else ""
        lines.append(
            f"| {r['parent']} -> {r['child']} | {r['stratum']} | {r['delta']:+.3f} | {ci} | {fmt_p(r['p_value'])} | "
            f"{r['n_clusters']}{fragile} | {r['clusters_child_better']}/{r['n_clusters']} | "
            f"{r['n_seeds_parent']}/{r['n_seeds_child']} | {dm} |"
        )
    lines += [
        "",
        "Notes:",
        "- delta = child - parent (negative = child better). 95% CI and p: cluster-jackknife t-test "
        "(`evaluation/stats.py`) with G year x season clusters and G-1 df. DM = Diebold-Mariano on "
        "seed-averaged per-window MSE (secondary; 'all' only). If they disagree, the cluster test is the headline.",
        "- `*` = fewer than 10 clusters: the result is fragile. The val split (2016-18) only has 9 clusters, and 5 "
        "for the extreme stratum, so these are development diagnostics. Headline inference uses rolling-origin folds.",
        "- Seeds (p/c): persistence and climatology are deterministic (1 'seed'); only a neural model's seed "
        "variance enters the SE when compared with them.",
        "- Optimistic for the neural models: both were early-stopped on this same val split, so their val errors "
        "are slightly favourable relative to the baselines.",
        "- Known v1 limitation: `models/retrieval_lstm.py` spreads attention uniformly over zero-padded slots "
        "when a query has no eligible analogue (163/13,131 train windows; no val windows). RA-v1 is kept as "
        "originally built; the fix belongs to the v2 retrieval model.",
    ]
    (OUT_DIR / "g0_val_comparison.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[4:]))


if __name__ == "__main__":
    main()
